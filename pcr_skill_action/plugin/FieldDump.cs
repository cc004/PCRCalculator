using System;
using System.IO;
using System.Runtime.InteropServices;
using System.Text;
using System.Threading;
using Il2CppInterop.Runtime;

namespace PcrApiDump
{
    /// <summary>
    /// 在进程内把 il2cpp 的「类 / 字段(含偏移) / 方法(含 RVA 与签名)」全量导出，
    /// 产出 Il2CppDumper 的 dump.cs 等价物。
    ///
    /// 为什么要自己导：本游戏的 metadata header 被加壳器抹掉了（镜像里刷不到
    /// 0xFAB11BAF，也没有任何 header 的 stringOffset 指向那段字符串堆），
    /// Il2CppDumper / Cpp2IL 第一步 sanity 校验就过不去。
    /// 但 il2cpp 自身导出 241 个 il2cpp_* API，运行时这些结构全都在，
    /// 所以直接在进程里问它要，比解析 metadata 更权威。
    ///
    /// 输出（默认 &lt;BepInEx根&gt;\PcrApiDump）：
    ///   dump.cs        伪 C#：namespace/class/字段+偏移/方法+签名+RVA
    ///   classes.csv    image,namespace,class,flags,parent,instance_size,value_size
    ///   fields.csv     image,namespace,class,field,offset,type,flags
    ///   methods_sig.csv image,namespace,class,method,rva,flags,ret,params
    ///
    /// 全程只读；每个类单独 try/catch，个别类炸了不影响整体。
    /// </summary>
    internal static class FieldDump
    {
        private const int TypeFieldStatic = 0x10;
        private const int TypeFieldLiteral = 0x40;
        private static int _started;

        internal static void OnceAfterStart(string outDir)
        {
            if (Interlocked.Exchange(ref _started, 1) == 1) return;
            ThreadPool.QueueUserWorkItem(_ =>
            {
                Thread.Sleep(4000);
                try { Run(outDir); }
                catch (Exception e) { try { Plugin.Logger.LogError("[field-dump] " + e); } catch { } }
            });
        }

        private static string Ansi(IntPtr p)
        {
            return p == IntPtr.Zero ? "" : (Marshal.PtrToStringAnsi(p) ?? "");
        }

        private static string Csv(string s)
        {
            if (string.IsNullOrEmpty(s)) return "";
            if (s.IndexOfAny(new[] { ',', '"', '\n', '\r' }) < 0) return s;
            return "\"" + s.Replace("\"", "\"\"") + "\"";
        }

        private static string ClassFullName(IntPtr klass)
        {
            if (klass == IntPtr.Zero) return "";
            string ns = Ansi(IL2CPP.il2cpp_class_get_namespace(klass));
            string n = Ansi(IL2CPP.il2cpp_class_get_name(klass));
            return string.IsNullOrEmpty(ns) ? n : ns + "." + n;
        }

        private static unsafe void Run(string outDir)
        {
            Directory.CreateDirectory(outDir);
            int nClasses = 0, nFields = 0, nMethods = 0, nClassesErr = 0;

            var dump = new StreamWriter(Path.Combine(outDir, "dump.cs"), false, new UTF8Encoding(false));
            var fCls = new StreamWriter(Path.Combine(outDir, "classes.csv"), false, new UTF8Encoding(false));
            var fFld = new StreamWriter(Path.Combine(outDir, "fields.csv"), false, new UTF8Encoding(false));
            var fMth = new StreamWriter(Path.Combine(outDir, "methods_sig.csv"), false, new UTF8Encoding(false));
            var fEnum = new StreamWriter(Path.Combine(outDir, "enums.csv"), false, new UTF8Encoding(false));
            try
            {
                fCls.WriteLine("image,namespace,class,flags,parent,instance_size,value_size");
                fFld.WriteLine("image,namespace,class,field,offset,type,flags");
                fMth.WriteLine("image,namespace,class,method,rva,flags,ret,params");
                fEnum.WriteLine("enum,member,value");
                dump.WriteLine("// auto-generated by PcrApiDump.FieldDump (il2cpp API, in-process)");

                var domain = IL2CPP.il2cpp_domain_get();
                uint nAsm = 0;
                var asms = IL2CPP.il2cpp_domain_get_assemblies(domain, ref nAsm);
                for (uint a = 0; a < nAsm; a++)
                {
                    var asm = asms[(int)a];
                    if (asm == IntPtr.Zero) continue;
                    var image = IL2CPP.il2cpp_assembly_get_image(asm);
                    if (image == IntPtr.Zero) continue;
                    string imageName = Ansi(IL2CPP.il2cpp_image_get_name(image));

                    int ccount = (int)IL2CPP.il2cpp_image_get_class_count(image);
                    for (int c = 0; c < ccount; c++)
                    {
                        var klass = IL2CPP.il2cpp_image_get_class(image, (uint)c);
                        if (klass == IntPtr.Zero) continue;
                        try
                        {
                            string ns = Ansi(IL2CPP.il2cpp_class_get_namespace(klass));
                            string cn = Ansi(IL2CPP.il2cpp_class_get_name(klass));
                            int flags = IL2CPP.il2cpp_class_get_flags(klass);
                            var parent = IL2CPP.il2cpp_class_get_parent(klass);
                            string parentName = ClassFullName(parent);
                            int instSize = 0, valSize = 0;
                            try { instSize = (int)IL2CPP.il2cpp_class_instance_size(klass); } catch { }
                            try { uint align = 0; valSize = (int)IL2CPP.il2cpp_class_value_size(klass, ref align); } catch { }

                            nClasses++;
                            fCls.WriteLine(string.Join(",", Csv(imageName), Csv(ns), Csv(cn),
                                "0x" + flags.ToString("X"), Csv(parentName), instSize, valSize));

                            bool isValue = false, isEnum = false, isIface = false;
                            try { isValue = IL2CPP.il2cpp_class_is_valuetype(klass); } catch { }
                            try { isEnum = IL2CPP.il2cpp_class_is_enum(klass); } catch { }
                            try { isIface = IL2CPP.il2cpp_class_is_interface(klass); } catch { }

                            dump.WriteLine();
                            if (!string.IsNullOrEmpty(ns)) dump.WriteLine("namespace " + ns + " {");
                            string kind = isEnum ? "enum" : isIface ? "interface" : isValue ? "struct" : "class";
                            string inher = string.IsNullOrEmpty(parentName) || parentName == "System.Object"
                                ? "" : " : " + parentName;
                            dump.WriteLine(string.Format("  // {0} {1}  image={2} flags=0x{3:X} size=0x{4:X}",
                                kind, cn, imageName, flags, instSize));
                            dump.WriteLine("  " + kind + " " + cn + inher + " {");

                            // ---- 字段 ----
                            var fi = IntPtr.Zero;
                            while (true)
                            {
                                var f = IL2CPP.il2cpp_class_get_fields(klass, ref fi);
                                if (f == IntPtr.Zero) break;
                                string fname = Ansi(IL2CPP.il2cpp_field_get_name(f));
                                uint off = IL2CPP.il2cpp_field_get_offset(f);
                                int fflags = IL2CPP.il2cpp_field_get_flags(f);
                                string tname = "";
                                try { tname = Ansi(IL2CPP.il2cpp_type_get_name(IL2CPP.il2cpp_field_get_type(f))); } catch { }
                                bool isStatic = (fflags & TypeFieldStatic) != 0;
                                bool isLit = (fflags & TypeFieldLiteral) != 0;
                                nFields++;
                                fFld.WriteLine(string.Join(",", Csv(imageName), Csv(ns), Csv(cn), Csv(fname),
                                    "0x" + off.ToString("X"), Csv(tname), "0x" + fflags.ToString("X")));
                                // 枚举成员：把字面量值读出来（数字 ↔ 名字的映射，做 action_type 分析必需）
                                string enumVal = "";
                                if (isEnum && (isStatic || isLit))
                                {
                                    try
                                    {
                                        var box = Marshal.AllocHGlobal(16);
                                        try
                                        {
                                            for (int z = 0; z < 16; z++) Marshal.WriteByte(box, z, 0);
                                            IL2CPP.il2cpp_field_static_get_value(f, (void*)box);
                                            long v = Marshal.ReadInt32(box);
                                            enumVal = v.ToString();
                                            fEnum.WriteLine(string.Join(",", Csv(cn), Csv(fname), v));
                                        }
                                        finally { Marshal.FreeHGlobal(box); }
                                    }
                                    catch { }
                                }
                                dump.WriteLine(string.Format("    // {0}{1}{2}  +0x{3:X}{4}",
                                    isStatic ? "static " : "", isLit ? "const " : "", tname, off,
                                    enumVal == "" ? "" : "  = " + enumVal));
                                dump.WriteLine("    " + tname + " " + fname + ";");
                            }

                            // ---- 方法 ----
                            var mi2 = IntPtr.Zero;
                            while (true)
                            {
                                var m = IL2CPP.il2cpp_class_get_methods(klass, ref mi2);
                                if (m == IntPtr.Zero) break;
                                string mname = Ansi(IL2CPP.il2cpp_method_get_name(m));
                                uint mflags = 0;
                                try { uint iflags = 0; mflags = IL2CPP.il2cpp_method_get_flags(m, ref iflags); } catch { }
                                int rva = 0;
                                try
                                {
                                    var fn = Marshal.ReadIntPtr(m);
                                    if (fn != IntPtr.Zero) rva = (int)(fn.ToInt64() & 0x0FFFFFFF);
                                }
                                catch { }
                                string ret = "";
                                try { ret = Ansi(IL2CPP.il2cpp_type_get_name(IL2CPP.il2cpp_method_get_return_type(m))); } catch { }
                                int pc = 0;
                                try { pc = (int)IL2CPP.il2cpp_method_get_param_count(m); } catch { }
                                var ps = new StringBuilder();
                                for (int i = 0; i < pc; i++)
                                {
                                    if (i > 0) ps.Append(", ");
                                    string pn = "", pt = "";
                                    try { pn = Ansi(IL2CPP.il2cpp_method_get_param_name(m, (uint)i)); } catch { }
                                    try { pt = Ansi(IL2CPP.il2cpp_type_get_name(IL2CPP.il2cpp_method_get_param(m, (uint)i))); } catch { }
                                    ps.Append(pt).Append(' ').Append(pn);
                                }
                                nMethods++;
                                fMth.WriteLine(string.Join(",", Csv(imageName), Csv(ns), Csv(cn), Csv(mname),
                                    rva == 0 ? "" : "0x" + rva.ToString("X"), "0x" + mflags.ToString("X"),
                                    Csv(ret), Csv(ps.ToString())));
                                dump.WriteLine("    " + ret + " " + mname + "(" + ps + ");");
                            }
                            dump.WriteLine("  }");
                            if (!string.IsNullOrEmpty(ns)) dump.WriteLine("}");
                        }
                        catch (Exception e)
                        {
                            nClassesErr++;
                            try { Plugin.Logger.LogWarning("[field-dump] 类 #" + c + " 失败: " + e.Message); } catch { }
                        }
                    }
                }
            }
            finally
            {
                dump.Flush(); dump.Dispose();
                fCls.Flush(); fCls.Dispose();
                fFld.Flush(); fFld.Dispose();
                fMth.Flush(); fMth.Dispose();
                fEnum.Flush(); fEnum.Dispose();
            }
            Plugin.Logger.LogInfo(string.Format("[field-dump] 完成: {0} 类 / {1} 字段 / {2} 方法 / {3} 类失败 -> {4}",
                nClasses, nFields, nMethods, nClassesErr, outDir));
        }
    }
}



